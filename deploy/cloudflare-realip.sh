#!/usr/bin/env bash
# Makes nginx see the real visitor address when the site is behind Cloudflare.
# Without this every visitor appears to come from a Cloudflare address, and the
# login / registration / upload rate limits would be shared by all visitors.
# Run as root. Installed by deploy/install.sh and refreshed weekly by cron.
set -euo pipefail
out=/etc/nginx/conf.d/cloudflare-realip.conf
tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by cloudflare-realip.sh on $(date -u +%F). Do not edit."
  for v in v4 v6; do
    curl -fsS --max-time 20 "https://www.cloudflare.com/ips-$v" | while read -r ip || [ -n "$ip" ]; do
      # accept only plain address ranges, nothing else goes into the nginx file
      if [[ "$ip" =~ ^[0-9a-fA-F:.]+/[0-9]{1,3}$ ]]; then echo "set_real_ip_from $ip;"; fi
    done
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"
n=$(grep -c '^set_real_ip_from' "$tmp" || true)
[ "$n" -ge 10 ] || { echo "Cloudflare address list looks incomplete ($n ranges); nginx left unchanged."; exit 1; }
old=""; [ -f "$out" ] && { old=$(mktemp); cp "$out" "$old"; }
install -m 644 "$tmp" "$out"
if nginx -t 2>/dev/null; then systemctl reload nginx; echo "Cloudflare real-IP list updated ($n ranges)."
else
  if [ -n "$old" ]; then cp "$old" "$out"; else rm -f "$out"; fi
  echo "nginx rejected the new list; previous settings kept."; exit 1
fi
